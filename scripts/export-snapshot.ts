#!/usr/bin/env node
/**
 * Export a sanitized, secret-free static status snapshot (`snapshot.json`) for
 * GitHub Pages deployments that do not run a persistent HTTP relay.
 *
 * Usage:
 *   npm run snapshot:export                       # writes apps/web/public/snapshot.json
 *   npm run snapshot:export -- <output-file>      # writes to a custom path
 *
 * Every exported field passes through `redact()` and `assertNoSecrets()`, so
 * provider keys, database credentials, Telegram tokens, and admin tokens can
 * never appear in the published artifact.
 */

import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { assertNoSecrets, isMarketOpen, publicRuntimeConfig, redact, secretValues } from '@vortex/core';
import {
  lastSuccessfulJob,
  listAlerts,
  listDeliveries,
  listQuality,
  listSignals,
  signalCounts,
  workerStatus,
} from '@vortex/db';
import { WorkerRuntime } from '../apps/worker/src/runtime.js';
import { healthSnapshot } from '../apps/worker/src/jobs/maintenance.js';
import { modelRegistrySummary } from '../apps/worker/src/services/registry.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const defaultOut = join(root, 'apps', 'web', 'public', 'snapshot.json');

export async function buildSnapshot(runtime: WorkerRuntime): Promise<Record<string, unknown>> {
  const now = new Date();
  const nowMs = now.getTime();
  const secrets = secretValues(runtime.config);

  if (!runtime.db.connected || !runtime.db.client) {
    const empty = {
      ok: false,
      generatedAt: now.toISOString(),
      configured: false,
      error: runtime.db.detail || 'Database was not configured when this snapshot was built.',
      configured: false,
      health: null,
      summary: null,
      config: publicRuntimeConfig(runtime.config),
      signals: { signals: [], count: 0 },
    };
    const safe = redact(empty, secrets) as Record<string, unknown>;
    assertNoSecrets(safe, secrets);
    return safe;
  }

  const client = runtime.db.client;
  const [
    dbPing,
    workers,
    lastJob,
    rawQuality,
    budget,
    counts,
    deliveries,
    alerts,
    components,
    recentSignals,
    registry,
  ] =
    await Promise.all([
      runtime.pingDb(),
      workerStatus(client),
      lastSuccessfulJob(client),
      listQuality(client),
      runtime.keyPool.usageSnapshots(),
      signalCounts(client),
      listDeliveries(client, 50),
      listAlerts(client, false, 20),
      healthSnapshot(runtime),
      listSignals(client, { limit: 25 }),
      modelRegistrySummary(client),
    ]);

  const quality = rawQuality.map((row) => {
    const checkLag =
      row.checkedAt && Number.isFinite(Date.parse(row.checkedAt))
        ? Math.max(0, Math.round((nowMs - Date.parse(row.checkedAt)) / 1000))
        : 0;
    const ageSeconds = row.ageSeconds === null ? null : row.ageSeconds + checkLag;
    const stale =
      row.status === 'DEGRADED' ||
      row.status === 'DISCONNECTED' ||
      (ageSeconds !== null && ageSeconds > runtime.config.maxCandleAgeSeconds);
    let status = row.status;
    if (ageSeconds !== null && status === 'CONNECTED') {
      if (ageSeconds > 600) status = 'DISCONNECTED';
      else if (ageSeconds > runtime.config.maxCandleAgeSeconds) status = 'DEGRADED';
    }
    return { ...row, status, ageSeconds, stale };
  });

  const liveWorker = workers.find((w) => w.liveness === 'CONNECTED' || w.liveness === 'DEGRADED') ?? null;
  const latestWorker = liveWorker ?? workers[0] ?? null;
  const reportedLiveness = liveWorker ? liveWorker.liveness : latestWorker ? 'DISCONNECTED' : 'NOT VERIFIED';
  const pending = Object.entries(counts)
    .filter(([key]) => key.startsWith('PENDING:'))
    .reduce((acc, [, value]) => acc + value, 0);
  const decisive = (counts.WIN ?? 0) + (counts.LOSS ?? 0);
  const lastFinishedAt = lastJob ? (lastJob.finishedAt ?? lastJob.startedAt) : null;
  const ready = runtime.isReady();

  const payload = {
    ok: true,
    generatedAt: now.toISOString(),
    configured: true,
    health: {
      service: 'vortex-si-snapshot',
      status: dbPing.ok ? (ready.ready ? 'ok' : 'degraded') : 'degraded',
      version: runtime.config.engineVersion,
      uptimeSeconds: 0,
      database: dbPing,
      provider: { name: runtime.config.provider, synthetic: runtime.providerSynthetic },
      ready: ready.ready,
      reasons: ready.reasons,
      note: 'Static snapshot generated by GitHub Actions. No persistent HTTP relay is running; check snapshot age and lastSuccessfulJob.',
      timestamp: now.toISOString(),
    },
    summary: {
      generatedAt: now.toISOString(),
      marketOpen: isMarketOpen(now),
      worker: latestWorker
        ? {
            workerId: latestWorker.workerId,
            liveness: reportedLiveness,
            running: reportedLiveness === 'CONNECTED',
            secondsSince: latestWorker.secondsSince,
            lastJob: latestWorker.lastJob ?? lastJob?.jobName ?? null,
            lastJobAt: latestWorker.lastJobAt ?? lastFinishedAt,
            jobsCompleted: latestWorker.jobsCompleted,
            jobsFailed: latestWorker.jobsFailed,
            version: latestWorker.version,
          }
        : null,
      workerStatus: reportedLiveness,
      lastSuccessfulJob: lastJob
        ? {
            jobName: lastJob.jobName,
            slotKey: lastJob.slotKey,
            finishedAt: lastFinishedAt!,
            ageSeconds: Math.max(0, Math.round((nowMs - new Date(lastFinishedAt!).getTime()) / 1000)),
            durationMs: lastJob.durationMs,
            workerId: lastJob.workerId,
          }
        : null,
      marketData: quality,
      providerBudget: {
        enabledKeys: budget.summary.enabledKeys,
        usableKeys: budget.summary.activeKeys,
        dayCapacity: budget.summary.dayCapacity,
        dayUsed: budget.summary.dayUsed,
        dayRemainingPercent: Number(budget.summary.dayRemainingPercent.toFixed(2)),
        warnings: budget.summary.warnings,
      },
      signals: {
        inFlight: pending,
        wins: counts.WIN ?? 0,
        losses: counts.LOSS ?? 0,
        draws: counts.DRAW ?? 0,
        unresolved: counts.UNRESOLVED ?? 0,
        decisive,
        accuracy: decisive === 0 ? null : Number((((counts.WIN ?? 0) / decisive) * 100).toFixed(2)),
        note: 'Accuracy uses decisive outcomes only; unresolved records are reported separately and never counted as wins.',
      },
      telegram: {
        configuration: runtime.telegram.configuration(),
        sent: deliveries.filter((d) => d.status === 'SENT').length,
        failed: deliveries.filter((d) => d.status === 'FAILED').length,
        unconfirmed: deliveries.filter((d) => d.status === 'UNKNOWN').length,
      },
      components,
      model: registry.model,
      learning: registry.learning,
      alerts: alerts.map((a) => ({ severity: a.severity, code: a.code, title: a.title, lastSeenAt: a.lastSeenAt })),
    },
    config: publicRuntimeConfig(runtime.config),
    signals: {
      signals: recentSignals.map((s) => ({
        id: s.id,
        pair: s.pair,
        decision: s.decision,
        status: s.status,
        confidence: s.confidence,
        scheduledEntryAt: s.scheduledEntryAt,
        outcome: s.outcome,
        realizedPips: s.realizedPips,
        strategy: s.strategy,
      })),
      count: recentSignals.length,
    },
  };

  const safe = redact(payload, secrets) as Record<string, unknown>;
  assertNoSecrets(safe, secrets);
  return safe;
}

async function main(): Promise<void> {
  const outPath = process.argv[2] ? resolve(process.cwd(), process.argv[2]) : defaultOut;
  const runtime = await WorkerRuntime.create({
    manual: true,
    config: { role: 'worker', dbRequired: false },
  });
  try {
    const snapshot = await buildSnapshot(runtime);
    await mkdir(dirname(outPath), { recursive: true });
    await writeFile(outPath, `${JSON.stringify(snapshot, null, 2)}\n`, 'utf8');
    console.log(`exported sanitized snapshot to ${outPath} (configured=${String(snapshot.configured)})`);
  } finally {
    await runtime.close();
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  main().catch((error: unknown) => {
    console.error(`snapshot export failed: ${(error as Error).message}`);
    process.exitCode = 1;
  });
}
