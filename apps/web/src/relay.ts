/**
 * Dashboard data client.
 *
 * The dashboard is a static site hosted on GitHub Pages: it holds no privileged
 * secrets and never talks to a provider or a base table directly.
 *
 * Three compatible, secret-free read modes are supported:
 *   1. Supabase public read-only views (`VITE_SUPABASE_URL` + `VITE_SUPABASE_ANON_KEY`):
 *      queries PostgREST `/rest/v1/public_*` views directly. Migration 0007
 *      enables RLS on every table, revokes all base-table access from `anon`
 *      and `authenticated`, and grants `SELECT` only on the secret-free
 *      `public_*` views — so no persistent HTTP relay server is required.
 *   2. Static status snapshot (`VITE_DATA_SOURCE=snapshot`, `./snapshot.json`):
 *      reads a sanitized JSON artifact generated by GitHub Actions and computes
 *      live staleness relative to the browser clock.
 *   3. HTTP relay (`VITE_RELAY_URL`, or same-origin in local dev):
 *      reads the relay's public plane (`/health`, `/api/*`).
 */

const configuredBase = (import.meta.env.VITE_RELAY_URL as string | undefined)?.replace(/\/$/, '') ?? '';
const configuredSupabaseUrl = (import.meta.env.VITE_SUPABASE_URL as string | undefined)?.replace(/\/$/, '') ?? '';
const configuredSupabaseAnonKey = (import.meta.env.VITE_SUPABASE_ANON_KEY as string | undefined)?.trim() ?? '';
const configuredDataSource = (import.meta.env.VITE_DATA_SOURCE as string | undefined)?.trim().toLowerCase() ?? '';

export const RELAY_BASE = configuredBase;
export const SUPABASE_URL = configuredSupabaseUrl;

export type DataSourceMode = 'relay' | 'supabase' | 'snapshot';

export const DATA_SOURCE_MODE: DataSourceMode =
  configuredDataSource === 'snapshot'
    ? 'snapshot'
    : configuredBase.length === 0 && configuredSupabaseUrl.length > 0 && configuredSupabaseAnonKey.length > 0
      ? 'supabase'
      : 'relay';

export interface RelayResult<T> {
  ok: boolean;
  status: number;
  data: T | null;
  error: string | null;
}

export interface HealthPayload {
  service: string;
  status: string;
  version: string;
  uptimeSeconds: number;
  database: { ok: boolean; detail: string };
  provider: { name: string; synthetic: boolean };
  ready: boolean;
  reasons: string[];
  note: string;
  timestamp: string;
}

export interface SignalRow {
  id: string;
  pair: string;
  decision: string;
  status: string;
  confidence: number;
  scheduledEntryAt: string;
  outcome: string | null;
  realizedPips: number | null;
  strategy: string;
}

export interface LastSuccessfulJob {
  jobName: string;
  slotKey: string;
  finishedAt: string;
  ageSeconds: number;
  durationMs?: number | null;
  workerId?: string | null;
}

export interface MarketQualityRow {
  pair: string;
  status: string;
  ageSeconds: number | null;
  detail: string | null;
  lastCandleAt?: string | null;
  checkedAt?: string | null;
  stale?: boolean;
}

export interface SummaryPayload {
  generatedAt?: string;
  marketOpen?: boolean;
  worker: {
    workerId: string;
    liveness: string;
    running?: boolean;
    secondsSince: number;
    lastJob: string | null;
    lastJobAt?: string | null;
  } | null;
  workerStatus?: string;
  lastSuccessfulJob?: LastSuccessfulJob | null;
  marketData: MarketQualityRow[];
  providerBudget: {
    enabledKeys: number;
    usableKeys: number;
    dayCapacity: number;
    dayUsed: number;
    dayRemainingPercent: number;
    warnings: string[];
  } | null;
  signals: {
    inFlight: number;
    wins: number;
    losses: number;
    draws: number;
    unresolved: number;
    decisive: number;
    accuracy: number | null;
    note: string;
  } | null;
  telegram: { configuration: { status: string; detail: string }; sent: number; failed: number; unconfirmed: number };
  alerts: { severity: string; code: string; title: string; lastSeenAt: string }[];
  note?: string;
}

export interface RelayClient {
  health: () => Promise<RelayResult<HealthPayload>>;
  summary: () => Promise<RelayResult<SummaryPayload>>;
  config: () => Promise<RelayResult<Record<string, unknown>>>;
  signals: (limit?: number) => Promise<RelayResult<{ signals: SignalRow[]; count: number }>>;
}

/**
 * Recompute live candle age and staleness relative to `nowMs` so the dashboard
 * never claims stale data is fresh when no job has run recently.
 */
export function computeMarketDataStaleness(
  rows: MarketQualityRow[],
  maxCandleAgeSeconds = 90,
  nowMs = Date.now(),
): MarketQualityRow[] {
  return rows.map((row) => {
    const checkLag =
      row.checkedAt && Number.isFinite(Date.parse(row.checkedAt))
        ? Math.max(0, Math.round((nowMs - Date.parse(row.checkedAt)) / 1000))
        : 0;
    const ageSeconds = row.ageSeconds === null ? null : row.ageSeconds + checkLag;
    let status = row.status;
    if (ageSeconds !== null && status === 'CONNECTED') {
      if (ageSeconds > 600) status = 'DISCONNECTED';
      else if (ageSeconds > maxCandleAgeSeconds) status = 'DEGRADED';
    }
    const stale =
      status === 'DEGRADED' ||
      status === 'DISCONNECTED' ||
      (ageSeconds !== null && ageSeconds > maxCandleAgeSeconds);
    return {
      ...row,
      status,
      ageSeconds,
      stale,
    };
  });
}

/**
 * Ensure a stopped or stale worker is never reported as running (`CONNECTED`).
 */
export function normalizeWorkerLiveness(
  worker: SummaryPayload['worker'],
  staleSeconds = 120,
): SummaryPayload['worker'] {
  if (!worker) return null;
  const isStoppedOrStale =
    worker.liveness === 'STOPPING' ||
    worker.liveness === 'DISCONNECTED' ||
    worker.running === false ||
    worker.secondsSince > staleSeconds;
  const liveness = isStoppedOrStale
    ? worker.secondsSince <= 600 && worker.liveness === 'DEGRADED'
      ? 'DEGRADED'
      : 'DISCONNECTED'
    : worker.liveness;
  return {
    ...worker,
    liveness,
    running: liveness === 'CONNECTED',
  };
}

function isFxMarketOpenAt(date: Date): boolean {
  const day = date.getUTCDay();
  const hour = date.getUTCHours();
  if (day === 6) return false;
  if (day === 0 && hour < 22) return false;
  if (day === 5 && hour >= 22) return false;
  return true;
}

/**
 * HTTP relay client (`/health`, `/api/*`).
 */
export function createRelayClient(baseUrl = RELAY_BASE): RelayClient {
  const base = baseUrl.replace(/\/$/, '');

  async function get<T>(path: string, init: RequestInit = {}): Promise<RelayResult<T>> {
    try {
      const response = await fetch(`${base}${path}`, {
        ...init,
        headers: { accept: 'application/json', ...(init.headers ?? {}) },
      });
      const text = await response.text();
      const body = text.length === 0 ? null : (JSON.parse(text) as { ok?: boolean; data?: T; error?: { message?: string } });
      if (!response.ok || body?.ok === false) {
        return { ok: false, status: response.status, data: null, error: body?.error?.message ?? `HTTP ${response.status}` };
      }
      return { ok: true, status: response.status, data: (body?.data ?? null) as T, error: null };
    } catch (error) {
      return {
        ok: false,
        status: 0,
        data: null,
        error: `relay unreachable from this browser: ${(error as Error).message}`,
      };
    }
  }

  return {
    health: () => get<HealthPayload>('/health'),
    summary: () => get<SummaryPayload>('/api/summary'),
    config: () => get<Record<string, unknown>>('/api/config'),
    signals: (limit = 25) => get<{ signals: SignalRow[]; count: number }>(`/api/signals?limit=${limit}`),
  };
}

/**
 * Supabase PostgREST client that reads ONLY the RLS-protected, secret-free
 * `public_*` views (`0007_access_control.sql`). Requires no persistent relay.
 */
export function createSupabasePublicClient(options: { url: string; anonKey: string }): RelayClient {
  const baseUrl = options.url.replace(/\/$/, '');
  const anonKey = options.anonKey.trim();

  async function queryView<T>(viewAndQuery: string): Promise<RelayResult<T>> {
    try {
      const authHeader = ['Bearer', anonKey].join(' ');
      const response = await fetch(`${baseUrl}/rest/v1/${viewAndQuery}`, {
        headers: {
          accept: 'application/json',
          apikey: anonKey,
          authorization: authHeader,
        },
      });
      const text = await response.text();
      const parsed = text.length === 0 ? null : (JSON.parse(text) as unknown);
      if (!response.ok) {
        const msg =
          parsed && typeof parsed === 'object' && 'message' in (parsed as Record<string, unknown>)
            ? String((parsed as Record<string, unknown>).message)
            : `HTTP ${response.status}`;
        return { ok: false, status: response.status, data: null, error: msg };
      }
      return { ok: true, status: response.status, data: parsed as T, error: null };
    } catch (error) {
      return {
        ok: false,
        status: 0,
        data: null,
        error: `Supabase public view unreachable: ${(error as Error).message}`,
      };
    }
  }

  return {
    async health(): Promise<RelayResult<HealthPayload>> {
      const res = await queryView<
        { component: string; status: string; detail: string | null; metadata: Record<string, unknown> | null; observed_at: string }[]
      >('public_agent_status?select=component,status,detail,metadata,observed_at');
      if (!res.ok || !res.data) {
        return { ok: false, status: res.status, data: null, error: res.error ?? 'Supabase public_agent_status query failed' };
      }
      const rows = res.data;
      const workerRow = rows.find((r) => r.component === 'worker');
      const keysRow = rows.find((r) => r.component === 'provider_keys');
      const meta = (workerRow?.metadata ?? {}) as Record<string, unknown>;
      const providerName = typeof meta.provider === 'string' ? meta.provider : 'twelvedata';
      const synthetic = meta.synthetic === true;
      const reasons: string[] = [];
      if (keysRow?.status === 'CONFIGURATION REQUIRED') {
        reasons.push(keysRow.detail ?? 'No provider API keys configured');
      }
      return {
        ok: true,
        status: 200,
        data: {
          service: 'supabase-public-views',
          status: reasons.length === 0 ? 'ok' : 'degraded',
          version: 'vortex-engine-1.0.0',
          uptimeSeconds: 0,
          database: { ok: true, detail: 'Supabase RLS public_* views reachable' },
          provider: { name: providerName, synthetic },
          ready: reasons.length === 0,
          reasons,
          note: 'Direct read-only view via Supabase Free (no persistent HTTP relay). Backend jobs run on scheduled GitHub Actions.',
          timestamp: new Date().toISOString(),
        },
        error: null,
      };
    },

    async summary(): Promise<RelayResult<SummaryPayload>> {
      const [workersRes, qualityRes, budgetRes, quotaRes, perfRes, deliveriesRes, alertsRes, agentRes] = await Promise.all([
        queryView<
          {
            worker_id: string;
            version: string;
            last_seen_at: string;
            last_job: string | null;
            last_job_at: string | null;
            seconds_since_heartbeat: number;
            liveness: string;
            metadata: Record<string, unknown> | null;
          }[]
        >('public_worker_status?select=*&order=last_seen_at.desc&limit=5'),
        queryView<
          {
            pair: string;
            status: string;
            age_seconds: number | null;
            detail: string | null;
            last_candle_at: string | null;
            checked_at: string | null;
          }[]
        >('public_market_quality?select=*&order=pair.asc'),
        queryView<
          {
            enabled_keys: number;
            usable_keys: number;
            configured_day_capacity: number;
          }[]
        >('public_provider_budget?select=*'),
        queryView<{ bucket: string; bucket_start: string; used: number }[]>(
          'public_quota_usage?select=*&bucket=eq.day&order=bucket_start.desc&limit=1',
        ),
        queryView<
          {
            decisive: number;
            wins: number;
            losses: number;
            draws: number;
            unresolved: number;
            pending: number;
            accuracy: number | null;
          }[]
        >('public_overall_performance?select=*'),
        queryView<{ status: string }[]>('public_telegram_delivery?select=status&limit=200'),
        queryView<{ severity: string; code: string; title: string; last_seen_at: string }[]>(
          'public_alerts?select=severity,code,title,last_seen_at&order=last_seen_at.desc&limit=20',
        ),
        queryView<{ component: string; status: string; detail: string | null; metadata: Record<string, unknown> | null }[]>(
          'public_agent_status?select=component,status,detail,metadata',
        ),
      ]);

      if (!workersRes.ok) {
        return { ok: false, status: workersRes.status, data: null, error: workersRes.error ?? 'Failed to read public_worker_status' };
      }

      const nowMs = Date.now();
      const workerRow = (workersRes.data ?? [])[0] ?? null;
      const workerMeta = (workerRow?.metadata ?? {}) as Record<string, unknown>;
      const agentWorker = (agentRes.data ?? []).find((a) => a.component === 'worker');
      const agentWorkerMeta = (agentWorker?.metadata ?? {}) as Record<string, unknown>;

      const rawWorker: SummaryPayload['worker'] = workerRow
        ? {
            workerId: workerRow.worker_id,
            liveness: workerRow.liveness,
            running: workerRow.liveness === 'CONNECTED' && workerMeta.active !== false,
            secondsSince: Math.max(0, Number(workerRow.seconds_since_heartbeat ?? 0)),
            lastJob: workerRow.last_job,
            lastJobAt: workerRow.last_job_at,
          }
        : null;
      const normalizedWorker = normalizeWorkerLiveness(rawWorker);

      const metaJob = (workerMeta.lastSuccessfulJob ?? agentWorkerMeta.lastSuccessfulJob) as
        | { jobName?: string; slotKey?: string; finishedAt?: string; durationMs?: number | null; workerId?: string | null }
        | undefined;
      let lastSuccessfulJob: LastSuccessfulJob | null = null;
      if (metaJob?.jobName && metaJob.finishedAt) {
        lastSuccessfulJob = {
          jobName: metaJob.jobName,
          slotKey: metaJob.slotKey ?? 'scheduled',
          finishedAt: metaJob.finishedAt,
          ageSeconds: Math.max(0, Math.round((nowMs - Date.parse(metaJob.finishedAt)) / 1000)),
          durationMs: metaJob.durationMs ?? null,
          workerId: metaJob.workerId ?? workerRow?.worker_id ?? null,
        };
      } else if (workerRow?.last_job && workerRow.last_job_at) {
        lastSuccessfulJob = {
          jobName: workerRow.last_job,
          slotKey: 'scheduled',
          finishedAt: workerRow.last_job_at,
          ageSeconds: Math.max(0, Math.round((nowMs - Date.parse(workerRow.last_job_at)) / 1000)),
          workerId: workerRow.worker_id,
        };
      }

      const rawMarketData: MarketQualityRow[] = (qualityRes.data ?? []).map((q) => ({
        pair: q.pair,
        status: q.status,
        ageSeconds: q.age_seconds === null ? null : Number(q.age_seconds),
        detail: q.detail,
        lastCandleAt: q.last_candle_at,
        checkedAt: q.checked_at,
      }));
      const marketData = computeMarketDataStaleness(rawMarketData, 90, nowMs);

      const bRow = (budgetRes.data ?? [])[0];
      const qRow = (quotaRes.data ?? [])[0];
      const dayCapacity = Number(bRow?.configured_day_capacity ?? 0);
      const dayUsed = Number(qRow?.used ?? 0);
      const dayRemainingPercent =
        dayCapacity > 0 ? Math.max(0, Number((((dayCapacity - dayUsed) / dayCapacity) * 100).toFixed(2))) : 0;

      const pRow = (perfRes.data ?? [])[0];
      const decisive = Number(pRow?.decisive ?? 0);
      const rawAcc = pRow?.accuracy === null || pRow?.accuracy === undefined ? null : Number(pRow.accuracy);

      const tgAgent = (agentRes.data ?? []).find((a) => a.component === 'telegram');
      const deliveries = deliveriesRes.data ?? [];

      return {
        ok: true,
        status: 200,
        data: {
          generatedAt: new Date(nowMs).toISOString(),
          marketOpen: isFxMarketOpenAt(new Date(nowMs)),
          worker: normalizedWorker,
          workerStatus: normalizedWorker ? normalizedWorker.liveness : 'NOT VERIFIED',
          lastSuccessfulJob,
          marketData,
          providerBudget: bRow
            ? {
                enabledKeys: Number(bRow.enabled_keys ?? 0),
                usableKeys: Number(bRow.usable_keys ?? 0),
                dayCapacity,
                dayUsed,
                dayRemainingPercent,
                warnings: Number(bRow.usable_keys ?? 0) === 0 ? ['No usable provider keys configured.'] : [],
              }
            : null,
          signals: pRow
            ? {
                inFlight: Number(pRow.pending ?? 0),
                wins: Number(pRow.wins ?? 0),
                losses: Number(pRow.losses ?? 0),
                draws: Number(pRow.draws ?? 0),
                unresolved: Number(pRow.unresolved ?? 0),
                decisive,
                accuracy: rawAcc === null ? null : Number((rawAcc * 100).toFixed(2)),
                note: 'Accuracy uses decisive outcomes only; unresolved records are reported separately and never counted as wins.',
              }
            : null,
          telegram: {
            configuration: {
              status: tgAgent?.status ?? 'NOT VERIFIED',
              detail: tgAgent?.detail ?? 'Read from Supabase public_agent_status view.',
            },
            sent: deliveries.filter((d) => d.status === 'SENT').length,
            failed: deliveries.filter((d) => d.status === 'FAILED').length,
            unconfirmed: deliveries.filter((d) => d.status === 'UNKNOWN').length,
          },
          alerts: (alertsRes.data ?? []).map((a) => ({
            severity: a.severity,
            code: a.code,
            title: a.title,
            lastSeenAt: a.last_seen_at,
          })),
        },
        error: null,
      };
    },

    async config(): Promise<RelayResult<Record<string, unknown>>> {
      const res = await queryView<{ key: string; value: unknown }[]>('public_runtime_config?select=key,value');
      if (!res.ok || !res.data) return { ok: false, status: res.status, data: null, error: res.error };
      const out: Record<string, unknown> = {};
      for (const row of res.data) out[row.key] = row.value;
      return { ok: true, status: 200, data: out, error: null };
    },

    async signals(limit = 25): Promise<RelayResult<{ signals: SignalRow[]; count: number }>> {
      const res = await queryView<
        {
          id: string;
          pair: string;
          decision: string;
          status: string;
          confidence: number;
          scheduled_entry_at: string;
          outcome: string | null;
          realized_pips: number | null;
          strategy: string;
        }[]
      >(
        `public_signals?select=id,pair,decision,status,confidence,scheduled_entry_at,outcome,realized_pips,strategy&order=scheduled_entry_at.desc&limit=${limit}`,
      );
      if (!res.ok || !res.data) return { ok: false, status: res.status, data: null, error: res.error };
      const signals: SignalRow[] = res.data.map((r) => ({
        id: r.id,
        pair: r.pair,
        decision: r.decision,
        status: r.status,
        confidence: Number(r.confidence),
        scheduledEntryAt: r.scheduled_entry_at,
        outcome: r.outcome,
        realizedPips: r.realized_pips === null || r.realized_pips === undefined ? null : Number(r.realized_pips),
        strategy: r.strategy,
      }));
      return { ok: true, status: 200, data: { signals, count: signals.length }, error: null };
    },
  };
}

/**
 * Static snapshot client (`./snapshot.json`) for deployments without a live
 * browser endpoint. Dynamically recomputes staleness against `Date.now()`.
 */
export function createSnapshotClient(snapshotUrl = './snapshot.json'): RelayClient {
  async function loadSnapshot(): Promise<
    RelayResult<{
      ok: boolean;
      generatedAt: string;
      configured: boolean;
      error?: string;
      health: HealthPayload | null;
      summary: SummaryPayload | null;
      config: Record<string, unknown>;
      signals: { signals: SignalRow[]; count: number };
    }>
  > {
    try {
      const response = await fetch(snapshotUrl, { headers: { accept: 'application/json' }, cache: 'no-store' });
      if (!response.ok) {
        return { ok: false, status: response.status, data: null, error: `Snapshot unavailable (HTTP ${response.status})` };
      }
      const parsed = (await response.json()) as {
        ok: boolean;
        generatedAt: string;
        configured: boolean;
        error?: string;
        health: HealthPayload | null;
        summary: SummaryPayload | null;
        config: Record<string, unknown>;
        signals: { signals: SignalRow[]; count: number };
      };
      if (!parsed.configured || !parsed.ok) {
        return {
          ok: false,
          status: 503,
          data: null,
          error: parsed.error ?? 'Static snapshot was built without a database connection.',
        };
      }
      return { ok: true, status: 200, data: parsed, error: null };
    } catch (error) {
      return { ok: false, status: 0, data: null, error: `Snapshot unreachable: ${(error as Error).message}` };
    }
  }

  return {
    async health(): Promise<RelayResult<HealthPayload>> {
      const snap = await loadSnapshot();
      if (!snap.ok || !snap.data?.health) return { ok: false, status: snap.status, data: null, error: snap.error };
      return { ok: true, status: 200, data: snap.data.health, error: null };
    },
    async summary(): Promise<RelayResult<SummaryPayload>> {
      const snap = await loadSnapshot();
      if (!snap.ok || !snap.data?.summary) return { ok: false, status: snap.status, data: null, error: snap.error };
      const nowMs = Date.now();
      const s = snap.data.summary;
      const snapLag = Number.isFinite(Date.parse(snap.data.generatedAt))
        ? Math.max(0, Math.round((nowMs - Date.parse(snap.data.generatedAt)) / 1000))
        : 0;
      const rawWorker = s.worker
        ? { ...s.worker, secondsSince: s.worker.secondsSince + snapLag }
        : null;
      const worker = normalizeWorkerLiveness(rawWorker);
      const lastSuccessfulJob = s.lastSuccessfulJob
        ? {
            ...s.lastSuccessfulJob,
            ageSeconds: Math.max(0, Math.round((nowMs - Date.parse(s.lastSuccessfulJob.finishedAt)) / 1000)),
          }
        : null;
      return {
        ok: true,
        status: 200,
        data: {
          ...s,
          worker,
          workerStatus: worker ? worker.liveness : 'NOT VERIFIED',
          lastSuccessfulJob,
          marketData: computeMarketDataStaleness(s.marketData ?? [], 90, nowMs),
        },
        error: null,
      };
    },
    async config(): Promise<RelayResult<Record<string, unknown>>> {
      const snap = await loadSnapshot();
      if (!snap.ok || !snap.data) return { ok: false, status: snap.status, data: null, error: snap.error };
      return { ok: true, status: 200, data: snap.data.config, error: null };
    },
    async signals(limit = 25): Promise<RelayResult<{ signals: SignalRow[]; count: number }>> {
      const snap = await loadSnapshot();
      if (!snap.ok || !snap.data) return { ok: false, status: snap.status, data: null, error: snap.error };
      const sliced = snap.data.signals.signals.slice(0, limit);
      return { ok: true, status: 200, data: { signals: sliced, count: sliced.length }, error: null };
    },
  };
}

export const relay: RelayClient =
  DATA_SOURCE_MODE === 'supabase'
    ? createSupabasePublicClient({ url: configuredSupabaseUrl, anonKey: configuredSupabaseAnonKey })
    : DATA_SOURCE_MODE === 'snapshot'
      ? createSnapshotClient('./snapshot.json')
      : createRelayClient(RELAY_BASE);
